"""Build index.html: a gradio-lite (Pyodide) build that runs entirely in the browser.

A Hugging Face *static* Space is free, but it serves files only -- there is no server-side
Python. gradio-lite solves that by running Python in the browser through Pyodide. Because
Pyodide imports one flat module more reliably than a package tree, this script concatenates
the package into a single module, verifies the flattened source behaves identically to the
installed package, and then embeds it.

There is exactly one source of truth: the modules under routeraudit/. Nothing is hand-copied.

    python build_static.py          # writes index.html and checks the flattened module
"""
from __future__ import annotations

import html
import re
from pathlib import Path

HERE = Path(__file__).parent
# dependency order: validation -> estimate -> reporting -> api
MODULES = [
    HERE / "routeraudit" / "validation.py",
    HERE / "routeraudit" / "core" / "estimate.py",
    HERE / "routeraudit" / "reporting.py",
    HERE / "routeraudit" / "api.py",
]
GENERATOR = HERE / "examples" / "make_examples.py"

# continuation lines must start with horizontal whitespace: \s would match newlines
# and swallow the following statements (it ate the @dataclass decorator once).
_REL_IMPORT = re.compile(r"^from \.[\w.]* import .*$(?:\n[ \t]+.*$)*", re.M)
_FUTURE = re.compile(r"^from __future__ import annotations$", re.M)
_VERSION_IMPORT = re.compile(r"^from \. import __version__$", re.M)
_LOCAL_REL_IMPORT = re.compile(r"^[ \t]+from \.[\w.]* import [^\n(]*$\n", re.M)


def flatten() -> str:
    """Concatenate the package into one module, dropping intra-package imports."""
    parts = [
        '"""RouterAudit, flattened for the browser build. Generated by build_static.py.',
        "",
        "Do not edit: edit the modules under routeraudit/ and re-run the build.",
        '"""',
        "from __future__ import annotations",
        "",
        "__version__ = " + repr(_read_version()),
        "",
    ]
    for m in MODULES:
        src = m.read_text()
        src = _FUTURE.sub("", src)
        src = _REL_IMPORT.sub("", src)
        src = _VERSION_IMPORT.sub("", src)
        # function-local relative imports (e.g. `    from .reporting import render_report`)
        # are dropped line by line; in a flat module the name is already in scope. Handled
        # separately from the module-level pattern so a greedy continuation match cannot
        # swallow the indented statements that follow.
        src = _LOCAL_REL_IMPORT.sub("", src)
        # estimate.py is referenced as `est.` inside api.py; the flat module has no submodule
        src = src.replace("est.VAR_FLOOR", "VAR_FLOOR").replace("est.", "")
        parts.append(f"# {'=' * 74}\n# from {m.relative_to(HERE)}\n# {'=' * 74}")
        parts.append(src)
    return "\n".join(parts)


def _read_version() -> str:
    txt = (HERE / "routeraudit" / "__init__.py").read_text()
    return re.search(r'__version__ = "([^"]+)"', txt).group(1)


APP_SRC = '''
import json, zipfile, io, os
import pandas as pd
import gradio as gr

import routeraudit_lite as ra
import make_examples

PRIVACY = (
    "**Upload only synthetic, anonymized, or non-sensitive data.** Do not upload confidential "
    "conversations, personal information, credentials, or proprietary prompts. "
    "Everything here runs inside your own browser: no file is uploaded to any server."
)

os.makedirs("examples", exist_ok=True)
_EX_READY = False

def _ensure_examples():
    global _EX_READY
    if not _EX_READY:
        make_examples.main()
        _EX_READY = True

def read_table(path):
    if not path:
        return None
    if str(path).lower().endswith(".csv"):
        return pd.read_csv(path)
    if str(path).lower().endswith((".parquet", ".pq")):
        return pd.read_parquet(path)
    raise ValueError("Only CSV and Parquet files are accepted.")

def load_example():
    _ensure_examples()
    return ("examples/routed_log.csv", "examples/model_prices.csv",
            "examples/randomized_audit.csv", "examples/verified_outcomes.csv",
            "examples/traffic.csv")

def write_bundle(result):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("summary.csv", result.summary.to_csv(index=False))
        z.writestr("audit_queue.csv", result.audit_queue.to_csv(index=False))
        z.writestr("candidate_switches.csv", result.candidate_switches.to_csv(index=False))
        z.writestr("diagnostics.json", json.dumps(result.diagnostics, indent=2, default=str))
        z.writestr("assumptions.json", json.dumps(result.manifest, indent=2, default=str))
        z.writestr("run_manifest.json", json.dumps(result.manifest, indent=2, default=str))
        z.writestr("warnings.json", json.dumps(result.warnings, indent=2))
        z.writestr("report.html", result.report_html)
    out = "routeraudit_report.zip"
    with open(out, "wb") as fh:
        fh.write(buf.getvalue())
    return out

def run_analysis(log_f, price_f, audit_f, ver_f, traf_f, tol, horizon, budget,
                 vcost, conf, support, readout):
    empty = pd.DataFrame()
    try:
        log, prices = read_table(log_f), read_table(price_f)
        if log is None or prices is None:
            raise ValueError("A routed log and a model-price table are required. "
                             "Use 'Load bundled example' on the Data tab to try the app.")
        cfg = ra.AuditConfig(quality_tolerance=float(tol), future_requests=int(horizon),
                             audit_budget_usd=float(budget), verification_cost_usd=float(vcost),
                             confidence_level=float(conf), minimum_support=int(support),
                             audit_readout_size=int(readout))
        r = ra.analyze_trace(routed_log=log, model_prices=prices, config=cfg,
                             randomized_audit=read_table(audit_f),
                             verified_outcomes=read_table(ver_f),
                             traffic=read_table(traf_f))
        mode = ("**Mode A - audit plan.** No randomized audit was supplied, so this run proposes "
                "what evidence to collect. It does not claim any switch is valid."
                if r.mode == "plan" else
                "**Mode B - completed-audit analysis.** Estimates are routing-adjusted and "
                "pooled by inverse variance.")
        status = "### Analysis completed\\n\\n" + mode + "\\n"
        if r.warnings:
            status += "\\n**Warnings**\\n\\n" + "\\n".join("- " + w for w in r.warnings)
        return (status, r.summary, r.audit_queue, r.candidate_switches, r.diagnostics,
                gr.DownloadButton(value=write_bundle(r), visible=True))
    except Exception as exc:
        return ("### Analysis failed\\n\\n**" + type(exc).__name__ + ":** " + str(exc),
                empty, empty, empty, {}, gr.DownloadButton(visible=False))

with gr.Blocks(title="RouterAudit") as demo:
    gr.Markdown(
        "# RouterAudit\\n\\n"
        "Audit planning and uncertainty reporting for quality-constrained model-switch "
        "decisions.\\n\\n"
        "This demonstration **does not call models, modify production routing, guarantee "
        "savings, or establish measurement validity unless verified outcomes are supplied.** "
        "It runs entirely in your browser; nothing is sent to a server. Package version `"
        + ra.__version__ + "`.")

    with gr.Tab("1. Data"):
        gr.Markdown(PRIVACY)
        example_btn = gr.Button("Load bundled example", variant="secondary")
        with gr.Row():
            log_f = gr.File(label="Routed log (required)", file_types=[".csv"], type="filepath")
            price_f = gr.File(label="Model prices (required)", file_types=[".csv"], type="filepath")
        with gr.Row():
            audit_f = gr.File(label="Randomized audit results (optional)",
                              file_types=[".csv"], type="filepath")
            ver_f = gr.File(label="Verified target outcomes (optional)",
                            file_types=[".csv"], type="filepath")
        traf_f = gr.File(label="Traffic weights (optional)", file_types=[".csv"],
                         type="filepath")
        gr.Markdown(
            "**Schemas** &mdash; routed log: `request_id, request_type, model, score, "
            "request_cost_usd`; prices: `request_type, model, expected_cost_usd`; audit: "
            "`request_id, request_type, model, audit_score, audit_cost_usd`; verified: "
            "`request_id, request_type, model, verified_outcome`; traffic: "
            "`request_type, traffic_share`.")

    with gr.Tab("2. Decision settings"):
        gr.Markdown("Every default below is recorded in `assumptions.json` inside the report.")
        tol = gr.Number(label="Quality tolerance (delta)", value=0.02, minimum=0)
        horizon = gr.Number(label="Expected future requests", value=100000, minimum=1, precision=0)
        budget = gr.Number(label="Maximum audit budget ($)", value=10.0, minimum=0)
        vcost = gr.Number(label="Verification cost per validated outcome ($)", value=0.0, minimum=0)
        conf = gr.Slider(label="Confidence level", minimum=0.5, maximum=0.999, value=0.95, step=0.001)
        support = gr.Number(label="Minimum logged rows per model/request-type pair", value=8,
                            minimum=1, precision=0)
        readout = gr.Number(label="Randomized readouts per audited pair", value=30, minimum=1,
                            precision=0)
        run_btn = gr.Button("Run RouterAudit", variant="primary")

    with gr.Tab("3. Results"):
        status = gr.Markdown()
        summary = gr.Dataframe(label="Decision summary", interactive=False, wrap=True)
        queue = gr.Dataframe(label="Proposed audit queue", interactive=False, wrap=True)
        switches = gr.Dataframe(label="Candidate switches", interactive=False, wrap=True)
        diagnostics = gr.JSON(label="Diagnostics and assumptions")

    with gr.Tab("4. Report"):
        gr.Markdown("The ZIP contains `summary.csv`, `audit_queue.csv`, "
                    "`candidate_switches.csv`, `diagnostics.json`, `assumptions.json`, "
                    "`run_manifest.json`, `warnings.json` and `report.html`.")
        download = gr.DownloadButton(label="Download complete report", visible=False)

    example_btn.click(load_example, None, [log_f, price_f, audit_f, ver_f, traf_f])
    run_btn.click(run_analysis,
                  [log_f, price_f, audit_f, ver_f, traf_f, tol, horizon, budget, vcost,
                   conf, support, readout],
                  [status, summary, queue, switches, diagnostics, download])

demo.launch()
'''

# Pinned deliberately. The floating "latest" tag currently ships a gradio wheel whose
# huggingface-hub dependency micropip cannot resolve in Pyodide, so the page never boots.
# 5.45.0 is the version verified to render and run end to end (see tests/test_static_build.py).
LITE_VERSION = "5.45.0"

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>RouterAudit</title>
<script type="module" crossorigin
        src="https://cdn.jsdelivr.net/npm/@gradio/lite@{LITE}/dist/lite.js"></script>
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@gradio/lite@{LITE}/dist/lite.css" />
<style>
  /* Do not constrain the height of <gradio-lite>: a fixed 100% collapses the app so its
     controls render but are never visible. Let it size to its content. */
  html, body {{ margin: 0; padding: 0; }}
  gradio-lite {{ display: block; }}
</style>
</head>
<body>
<gradio-lite>
<!-- No <gradio-requirements> block on purpose. pandas, numpy and jinja2 already ship inside
     the gradio wheel that gradio-lite bundles. Declaring them makes micropip re-resolve
     gradio from PyPI, which fails with "Can't find a pure Python 3 wheel for
     'huggingface-hub<1.0,>=0.33.5'" and the page never boots. -->
<gradio-file name="routeraudit_lite.py">
{package}
</gradio-file>

<gradio-file name="make_examples.py">
{generator}
</gradio-file>

<gradio-file name="app.py" entrypoint>
{app}
</gradio-file>
</gradio-lite>
</body>
</html>
"""


def main() -> None:
    flat = flatten()
    _verify(flat)
    gen = GENERATOR.read_text().replace(
        'HERE = os.path.dirname(os.path.abspath(__file__))', 'HERE = "examples"')
    page = PAGE.format(LITE=LITE_VERSION,
                       package=html.escape(flat, quote=False),
                       generator=html.escape(gen, quote=False),
                       app=html.escape(APP_SRC, quote=False))
    out = HERE / "index.html"
    out.write_text(page, encoding="utf-8")
    print(f"wrote {out}  ({len(page) / 1024:.0f} KB)")
    print(f"  flattened package: {len(flat) / 1024:.0f} KB")
    print("  browser deps: none declared (pandas/numpy/jinja2 ship with gradio-lite)")


def _verify(flat: str) -> None:
    """Import the flattened module and check it matches the installed package exactly."""
    import sys
    import types
    import pandas as pd

    name = "routeraudit_lite_check"
    mod = types.ModuleType(name)
    mod.__file__ = "routeraudit_lite.py"
    # dataclasses resolves sys.modules[cls.__module__], so register before executing
    sys.modules[name] = mod
    try:
        exec(compile(flat, "routeraudit_lite.py", "exec"), mod.__dict__)
    finally:
        sys.modules.pop(name, None)

    import routeraudit as pkg
    ex = HERE / "examples"
    if not (ex / "routed_log.csv").exists():
        print("  (examples missing, skipping equivalence check)")
        return
    kw = dict(routed_log=pd.read_csv(ex / "routed_log.csv"),
              model_prices=pd.read_csv(ex / "model_prices.csv"),
              randomized_audit=pd.read_csv(ex / "randomized_audit.csv"),
              verified_outcomes=pd.read_csv(ex / "verified_outcomes.csv"),
              traffic=pd.read_csv(ex / "traffic.csv"))
    a = pkg.analyze_trace(config=pkg.AuditConfig(verification_cost_usd=0.25), **kw)
    b = mod.analyze_trace(config=mod.AuditConfig(verification_cost_usd=0.25), **kw)
    assert a.summary.equals(b.summary), "flattened summary differs"
    assert a.candidate_switches.equals(b.candidate_switches), "flattened switches differ"
    assert a.audit_queue.equals(b.audit_queue), "flattened queue differs"
    assert a.warnings == b.warnings, "flattened warnings differ"
    print("  equivalence check: flattened module matches the package exactly")


if __name__ == "__main__":
    main()
